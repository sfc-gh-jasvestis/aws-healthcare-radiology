-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT dept.ID AS ENTITY_ID, dept.NAME AS ENTITY_NAME,
       dept.REGION, dept.CATEGORY, dept.SERVICE_TIER, dept.STATUS,
       dept.PLANNED_STUDIES_90D,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.COMPLETED_COUNT) AS COMPLETED_COUNT,
       SUM(observation.IN_TARGET_COUNT) AS IN_TARGET_COUNT,
       SUM(observation.ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(observation.BREACH_COUNT) AS BREACH_COUNT,
       SUM(observation.REVIEW_OPENED) AS REVIEW_COUNT,
       SUM(observation.QA_DUE) AS QA_DUE,
       SUM(observation.QA_COMPLETED) AS QA_COMPLETED,
       100.0 * SUM(observation.COMPLETED_COUNT) / NULLIF(dept.PLANNED_STUDIES_90D, 0) AS VOLUME_VS_PLAN_PCT,
       100.0 * (SUM(observation.COMPLETED_COUNT) - SUM(observation.IN_TARGET_COUNT)) / NULLIF(SUM(observation.COMPLETED_COUNT), 0) AS OUTSIDE_TARGET_PCT,
       100.0 * SUM(observation.BREACH_COUNT) / NULLIF(SUM(observation.ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT,
       100.0 * SUM(observation.QA_COMPLETED) / NULLIF(SUM(observation.QA_DUE), 0) AS QA_COMPLIANCE_PCT,
       AVG(observation.TAT_HOURS) AS AVG_TAT_HOURS,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.DEPT_DAILY observation
JOIN RAW.DEPARTMENTS dept ON dept.ID = observation.ENTITY_ID
GROUP BY dept.ID, dept.NAME, dept.REGION, dept.CATEGORY, dept.SERVICE_TIER, dept.STATUS, dept.PLANNED_STUDIES_90D;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(COMPLETED_COUNT) AS COMPLETED_COUNT, SUM(IN_TARGET_COUNT) AS IN_TARGET_COUNT,
       SUM(ESCALATION_COUNT) AS ESCALATION_COUNT, SUM(BREACH_COUNT) AS BREACH_COUNT,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT
FROM RAW.DEPT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.DRIVER_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT DELAY_DRIVER, SUM(ESCALATION_COUNT) AS ESCALATION_COUNT,
       SUM(BREACH_COUNT) AS BREACH_COUNT,
       SUM(REVIEW_OPENED) AS REVIEW_COUNT,
       COUNT(DISTINCT ENTITY_ID) AS DEPTS_AFFECTED,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(ESCALATION_COUNT), 0) AS ESCALATION_CONFIRM_PCT
FROM RAW.DEPT_DAILY
WHERE ESCALATION_COUNT > 0
GROUP BY DELAY_DRIVER;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ESCALATION_COUNT) AS SIGNALS, SUM(BREACH_COUNT) AS CONFIRMED,
         SUM(REVIEW_OPENED) AS REVIEWS, SUM(COMPLETED_COUNT) AS COMPLETED, SUM(IN_TARGET_COUNT) AS IN_TARGET,
         AVG(TAT_HOURS) AS AVG_TAT, SUM(BACKLOG_STUDIES) AS BACKLOG_TOTAL,
         SUM(QA_DUE) AS QA_DUE, SUM(QA_COMPLETED) AS QA_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.DEPT_DAILY
), portfolio AS (SELECT COUNT(*) AS DEPT_COUNT, SUM(PLANNED_STUDIES_90D) AS TARGET FROM RAW.DEPARTMENTS),
fleet AS (
  SELECT 100.0 * SUM(QA_CERTIFIED) / NULLIF(SUM(SCANNERS_INSTALLED), 0) AS COVERAGE_PCT,
         SUM(CERT_PENDING) AS PENDING
  FROM RAW.SCANNER_FLEET
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Study Volume vs Plan' AS TITLE,
         100.0 * COMPLETED / NULLIF(TARGET, 0) AS VALUE_NUM, '%' AS UNIT FROM observations CROSS JOIN portfolio
  UNION ALL SELECT 2, 'Studies Completed', COMPLETED, '' FROM observations
  UNION ALL SELECT 3, 'Reports Outside TAT Target', 100.0 * (COMPLETED - IN_TARGET) / NULLIF(COMPLETED, 0), '%' FROM observations
  UNION ALL SELECT 4, 'Escalation Confirmation Rate', 100.0 * CONFIRMED / NULLIF(SIGNALS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Worklist Escalations', SIGNALS, '' FROM observations
  UNION ALL SELECT 6, 'Confirmed Priority TAT Breaches', CONFIRMED, '' FROM observations
  UNION ALL SELECT 7, 'Breach Reviews Opened', REVIEWS, '' FROM observations
  UNION ALL SELECT 8, 'Scanner QA Compliance', 100.0 * QA_COMPLETED / NULLIF(QA_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Departments Active', DEPT_COUNT, '' FROM portfolio
  UNION ALL SELECT 10, 'Scanner QA Certification', COVERAGE_PCT, '%' FROM fleet
  UNION ALL SELECT 11, 'Scanner Certifications Pending', PENDING, '' FROM fleet
  UNION ALL SELECT 12, 'Average Report TAT (hours)', AVG_TAT, '' FROM observations
  UNION ALL SELECT 13, 'Unread Backlog (study-days)', BACKLOG_TOTAL, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.DRIVER_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
